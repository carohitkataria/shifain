/** Russian counts take one of three forms: 1 врач, 2 врача, 5 врачей. */
const ruPlural = (n: number, one: string, few: string, many: string) => {
  const tens = n % 100;
  const units = n % 10;
  if (tens >= 11 && tens <= 14) return many;
  if (units === 1) return one;
  if (units >= 2 && units <= 4) return few;
  return many;
};

